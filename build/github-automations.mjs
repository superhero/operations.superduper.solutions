import { readFile, writeFile } from 'node:fs/promises';
import { gzipSync } from 'node:zlib';
const input = new URL('../src/lib/github-automation-contracts.json', import.meta.url);
const output = new URL('../src/lib/github-automation-data.ts', import.meta.url);
const bytes = await readFile(input);
JSON.parse(bytes);
if (bytes.length > 1048576) throw Error('GitHub automation contracts exceed their declared bound.');
const packed = gzipSync(bytes, { level: 9 }).toString('base64');
const source = `// Copyright (C) 2026 Erik Landvall
// SPDX-License-Identifier: AGPL-3.0-only
// See LICENSE and LICENSE-ADDITIONAL-TERMS.
// Generated by build/github-automations.mjs; canonical source is the adjacent JSON.
import { gunzipSync } from 'fflate';
const packed = ${JSON.stringify(packed)};
const expectedBytes = ${bytes.length};
let decoded: string | undefined;
export function decodeGithubAutomationData(): unknown {
  if (decoded === undefined) {
    const compressed = Uint8Array.from(atob(packed), value => value.charCodeAt(0));
    if (compressed.length < 18 || new DataView(compressed.buffer).getUint32(compressed.length - 4, true) !== expectedBytes)
      throw new Error('Invalid GitHub automation contract length.');
    const bytes = gunzipSync(compressed);
    if (bytes.length !== expectedBytes) throw new Error('Incomplete GitHub automation contracts.');
    decoded = new TextDecoder('utf-8', { fatal: true }).decode(bytes);
  }
  return JSON.parse(decoded);
}
`;
if (process.argv.includes('--check')) {
  if (await readFile(output, 'utf8') !== source) throw Error('GitHub automation data must be regenerated.');
} else await writeFile(output, source);
console.log(JSON.stringify({ bytes: bytes.length, packedBytes: packed.length, checked: process.argv.includes('--check') }));
