import * as Gherkin from '@cucumber/gherkin';
import * as Messages from '@cucumber/messages';
import { normalizeTags, tagsMatch, tagsFunction } from './tags.mjs';

const ids = Messages.IdGenerator.uuid();
const gherkinParser = new Gherkin.Parser(new Gherkin.AstBuilder(ids), new Gherkin.GherkinClassicTokenMatcher());
const mdParser = new Gherkin.Parser(new Gherkin.AstBuilder(ids), new Gherkin.GherkinInMarkdownTokenMatcher());

/** Stable across checkout roots; a project supplies the other identity component. */
export function relativeFeatureUri(filename, root = '') {
  const normalized = filename.replaceAll('\\', '/');
  const prefix = root.replaceAll('\\', '/').replace(/\/$/, '');
  return prefix && normalized.startsWith(`${prefix}/`)
    ? normalized.slice(prefix.length + 1) : normalized;
}

export function renderGherkin(src, config, isMarkdown, filename = '') {
    const document = isMarkdown ? mdParser.parse(src) : gherkinParser.parse(src);
    const feature = document.feature;
    if (!feature) throw new SyntaxError(`No Gherkin Feature found in ${filename}`);
    const uri = relativeFeatureUri(filename, config.root);
    const selectedTags = tagsFunction(config.tagExpression);
    const featureTags = normalizeTags(feature.tags.map(tag => tag.name));
    const commonInfo = { feature: `${feature.keyword}: ${feature.name}`, tags: featureTags, config };
    const header = `// Generated by quickpickle-1.11.2-operations.1
import { test } from ${JSON.stringify(config.testModule || 'vitest')};
import { describe, beforeAll, afterAll } from 'vitest';
import { gherkinStep, applyHooks, getWorldConstructor, runScenario, hookReportError } from 'quickpickle';
const World = getWorldConstructor();
const common = { info: ${JSON.stringify(commonInfo)} };
beforeAll(async () => {
  try { await applyHooks('beforeAll', common); }
  catch (error) { throw hookReportError(error); }
});
afterAll(async () => {
  try { await applyHooks('afterAll', common); }
  catch (error) { throw hookReportError(error); }
});
`;
    const substitute = (text, values) => String(text).replace(/<([^>]+)>/g, (match, name) => Object.prototype.hasOwnProperty.call(values, name) ? values[name] : match);
    const stepCode = (step, index, values, background = false, sequence = [step]) => {
        const text = substitute(step.text, values);
        let data;
        if (step.dataTable) data = step.dataTable.rows.map(row => row.cells.map(cell => substitute(cell.value, values)));
        else if (step.docString) data = { content: substitute(step.docString.content, values), mediaType: step.docString.mediaType || null };
        const type = getStepType(sequence, index);
        return `// qp-source:${step.location.line}\nawait gherkinStep(${JSON.stringify(type)}, ${JSON.stringify(text)}, state, ${step.location.line}, ${background ? -index - 1 : index + 1}, undefined, ${JSON.stringify(data) ?? 'undefined'});`;
    };
    function childrenCode(children, inheritedTags, backgrounds, rule) {
        let output = '';
        const background = children.find(child => child.background)?.background;
        if (background) backgrounds = [...backgrounds, ...background.steps];
        for (const child of children) {
            if (child.rule) {
                const nextRule = child.rule;
                output += `describe(${JSON.stringify(`${nextRule.keyword}: ${nextRule.name}`)}, () => {\n${childrenCode(nextRule.children, normalizeTags([...inheritedTags, ...nextRule.tags.map(tag => tag.name)]), backgrounds, nextRule.name)}\n});\n`;
                continue;
            }
            if (!child.scenario) continue;
            const scenario = child.scenario;
            const scenarioTags = normalizeTags([...inheritedTags, ...scenario.tags.map(tag => tag.name)]);
            const groups = scenario.examples?.length ? scenario.examples.map((examples, block) => ({
                block, tags: normalizeTags([...scenarioTags, ...examples.tags.map(tag => tag.name)]),
                rows: (examples.tableBody || []).map((row, rowIndex) => ({
                    line: row.location.line, rowIndex,
                    values: Object.fromEntries(examples.tableHeader.cells.map((cell, index) => [cell.value, row.cells[index]?.value ?? ''])),
                })),
            })) : [{ block: -1, tags: scenarioTags, rows: [{ values: {}, line: scenario.location.line, rowIndex: -1 }] }];
            for (const group of groups) for (const row of group.rows) {
                const exploded = explodeTags(config.explodeTags || [], group.tags);
                for (const [explodeIndex, tags] of exploded.entries()) {
                    if (!selectedTags(tags)) continue;
                    const attrs = [
                        tagsMatch(config.todoTags, tags) ? '.todo' : '',
                        tagsMatch(config.skipTags, tags) ? '.skip' : '',
                        tagsMatch(config.failTags, tags) ? '.fails' : '',
                        tagsMatch(config.sequentialTags, tags) ? '.sequential' : tagsMatch(config.concurrentTags, tags) ? '.concurrent' : '',
                    ].join('');
                    const name = substitute(scenario.name, row.values);
                    const rowLabel = group.block < 0 ? '' : ` [Examples ${group.block + 1}, row ${row.rowIndex + 1}]`;
                    const title = `${scenario.keyword}: ${name}${rowLabel}${tags.length ? ` (${tags.join(' ')})` : ''}`;
                    const metadata = {
                        id: `${uri}:${scenario.location.line}:${group.block}:${row.rowIndex}:${explodeIndex}`,
                        uri, line: scenario.location.line, column: scenario.location.column,
                        exampleLine: row.line, exampleBlock: group.block, exampleRow: row.rowIndex,
                        tags, rule,
                        steps: [...backgrounds, ...scenario.steps].map(step => ({ text: substitute(step.text, row.values), line: step.location.line })),
                    };
                    const info = { ...commonInfo, scenario: name, tags, rule,
                        steps: scenario.steps.map(step => substitute(step.text, row.values)),
                        config, gherkin: metadata };
                    const body = [...backgrounds.map((step, index) => stepCode(step, index, row.values, true, backgrounds)), ...scenario.steps.map((step, index) => stepCode(step, index, row.values, false, scenario.steps))].join('\n');
                    output += `// qp-source:${scenario.location.line}\ntest${attrs}(${JSON.stringify(title)}, { meta: { gherkin: ${JSON.stringify(metadata)} } }, async function ({ task }) {\nconst context = arguments[0];\nawait runScenario(context, World, { ...${JSON.stringify(info)}, common }, async (state) => {\n${body}\n});\n});\n`;
                }
            }
        }
        return output;
    }
    return `${header}\ndescribe(${JSON.stringify(`${feature.keyword}: ${feature.name}`)}, () => {\n${childrenCode(feature.children, featureTags, [], undefined)}\n});\n`;
}

export function featureSourceMap(code, src, filename) {
    const alphabet = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/';
    const vlq = value => {
        let encoded = '', number = value < 0 ? ((-value) << 1) | 1 : value << 1;
        do { let digit = number & 31; number >>>= 5; if (number) digit |= 32; encoded += alphabet[digit]; } while (number);
        return encoded;
    };
    let sourceLine = 0, previousLine = 0;
    const mappings = code.split('\n').map(line => {
        const match = /^\/\/ qp-source:(\d+)$/.exec(line);
        if (match) sourceLine = Number(match[1]) - 1;
        const segment = `${vlq(0)}${vlq(0)}${vlq(sourceLine - previousLine)}${vlq(0)}`;
        previousLine = sourceLine;
        return segment;
    }).join(';');
    return { version: 3, file: filename, sources: [filename], sourcesContent: [src], names: [], mappings };
}

function getStepType(steps, idx) {
    switch (steps[idx].keywordType) {
        case 'Context':
        case 'Action':
        case 'Outcome':
            return steps[idx].keywordType;
        default:
            if (idx)
                return getStepType(steps, idx - 1);
            return 'Context';
    }
}
/**
 * Creates a 2d array of all possible combinations of the items in the input array
 * @param arr A 2d array of strings
 * @returns A 2d array of all possible combinations of the items in the input array
 */
export function explodeArray(arr) {
    if (arr.length === 0)
        return [[]];
    arr = arr.map(subArr => {
        return subArr.length ? subArr : [''];
    });
    const [first, ...rest] = arr;
    const subCombinations = explodeArray(rest);
    return first.flatMap(item => subCombinations.map(subCombo => [item, ...subCombo].filter(Boolean)));
}
/**
 * This function "explodes" any tags in the "explodeTags" setting and returns all possible
 * combinations of all the tags. The theory is that it allows you to write one Scenario that
 * runs multiple times in different ways; e.g. with and without JS or in different browsers.
 *
 * To take this case as an example, if the explodeTags are:
 * ```
 * [
 *   ['nojs', 'js'],
 *   ['firefox', 'chromium', 'webkit'],
 * ]
 * ```
 *
 * And the testTags are:
 * ```
 * ['nojs', 'js', 'snapshot']
 * ```
 *
 * Then the function will return:
 * ```
 * [
 *   ['nojs', 'snapshot'],
 *   ['js', 'snapshot'],
 * ]
 * ```
 *
 * In that case, the test will be run twice.
 *
 * @param explodeTags the 2d array of tags that should be exploded
 * @param testTags the tags to test against
 * @returns a 2d array of all possible combinations of tags
 */
export function explodeTags(explodeTags, testTags) {
    if (!explodeTags.length)
        return [testTags];
    let tagsToTest = [...testTags];
    // gather a 2d array of items that are shared between tags and each array in explodeTags
    // and then remove those items from the tags array
    const sharedTags = explodeTags.map(tagList => {
        let items = tagList.filter(tag => tagsToTest.includes(tag));
        if (items.length)
            items.forEach(item => tagsToTest.splice(tagsToTest.indexOf(item), 1));
        return items;
    });
    // then, build a 2d array of all possible combinations of the shared tags
    let combined = explodeArray(sharedTags);
    // finally, return the list
    return combined.length ? combined.map(arr => [...tagsToTest, ...arr]) : [testTags];
}
